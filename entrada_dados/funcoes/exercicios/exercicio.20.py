def cadastro_simples():
    nome = input("Nome: ")
    idade = input("Idade: ")
    profissao = input("Profissão: ")
    cidade = input("Cidade: ")

    print("\n======= CADASTRO =======")
    print(f"Nome: {nome}")
    print(f"Idade: {idade} anos")
    print(f"Profissão: {profissao}")
    print(f"Cidade: {cidade}")

cadastro_simples()